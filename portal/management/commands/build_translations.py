# The command ships one catalogue per language; every language is translated for
# the whole set of interface strings or it falls back to English as a whole.
MSGIDS = BASE_MSGIDS + EXTRA_MSGIDS + ACCOUNT_MSGIDS
CATALOG = {lang: BASE_CATALOG[lang] + EXTRA_CATALOG[lang] + ACCOUNT_CATALOG[lang]
           for lang in BASE_CATALOG}

PO_HEADER = (
    'Project-Id-Version: JanSutra AI\n'
    'MIME-Version: 1.0\n'
    'Content-Type: text/plain; charset=UTF-8\n'
    'Content-Transfer-Encoding: 8bit\n'
    'Plural-Forms: nplurals=2; plural=(n != 1);\n'
)


def _escape(text):
    return text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def _po_text(lang, entries):
    blocks = ['msgid ""', 'msgstr ""']
    for line in PO_HEADER.rstrip('\n').split('\n'):
        blocks.append('"%s\\n"' % _escape(line))
    blocks.append('')
    for msgid in entries:
        blocks.append('msgid "%s"' % _escape(msgid))
        blocks.append('msgstr "%s"' % _escape(entries[msgid]))
        blocks.append('')
    return '\n'.join(blocks) + '\n'


def _mo_bytes(entries):
    """Compile a msgid→msgstr mapping into GNU gettext .mo (little endian)."""
    items = sorted(((k.encode('utf-8'), v.encode('utf-8')) for k, v in entries.items()),
                   key=lambda pair: pair[0])
    count = len(items)
    header_size = 7 * 4
    orig_table = header_size
    trans_table = header_size + 8 * count
    cursor = header_size + 16 * count

    orig_offsets, orig_blob = [], b''
    for msgid, _ in items:
        orig_offsets.append((len(msgid), cursor))
        orig_blob += msgid + b'\x00'
        cursor += len(msgid) + 1
    trans_offsets, trans_blob = [], b''
    for _, msgstr in items:
        trans_offsets.append((len(msgstr), cursor))
        trans_blob += msgstr + b'\x00'
        cursor += len(msgstr) + 1

    out = struct.pack('<7I', 0x950412DE, 0, count, orig_table, trans_table, 0, 0)
    for length, offset in orig_offsets:
        out += struct.pack('<2I', length, offset)
    for length, offset in trans_offsets:
        out += struct.pack('<2I', length, offset)
    return out + orig_blob + trans_blob


class Command(BaseCommand):
    help = 'Build locale/<lang>/LC_MESSAGES/django.{po,mo} for every supported Indian language.'

    def handle(self, *args, **options):
        locale_root = Path(settings.LOCALE_PATHS[0])
        built = []
        for lang, values in CATALOG.items():
            if len(values) != len(MSGIDS):
                raise SystemExit(f'{lang}: expected {len(MSGIDS)} translations, got {len(values)}')
            entries = {msgid: value for msgid, value in zip(MSGIDS, values) if value}
            entries[''] = PO_HEADER  # gettext metadata header
            target = locale_root / lang / 'LC_MESSAGES'
            target.mkdir(parents=True, exist_ok=True)
            (target / 'django.po').write_text(_po_text(lang, entries), encoding='utf-8')
            (target / 'django.mo').write_bytes(_mo_bytes(entries))
            built.append(lang)
        self.stdout.write(self.style.SUCCESS(
            f'Built {len(built)} language catalogues: ' + ', '.join(built)))
